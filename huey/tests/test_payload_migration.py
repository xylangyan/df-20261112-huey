import datetime
import pickle

from huey.api import MemoryHuey
from huey.consumer import Worker
from huey.constants import TASK_PAYLOAD_V1
from huey.constants import TASK_PAYLOAD_VERSION_UNKNOWN
from huey.exceptions import InvalidTaskPayload
from huey.exceptions import UnknownTaskVersion
from huey.registry import Envelope
from huey.registry import Message
from huey.registry import identify_payload_version
from huey.signals import SIGNAL_DEAD_LETTER
from huey.tests.base import BaseTestCase


class TestPayloadMigration(BaseTestCase):
    """
    End-to-end migration behavior: a queue pre-seeded with legacy (v1)
    records, then mixed with current (v2) records and an unreadable record
    carrying an unknown payload version.
    """

    def get_huey(self):
        return MemoryHuey(utc=False)

    def _make_tasks(self):
        calls = []

        @self.huey.task()
        def add(a, b, tag=None):
            calls.append((a, b, tag))
            return a + b

        @self.huey.task()
        def follow(value, source=None):
            calls.append(('follow', value, source))
            return value

        return calls, add, follow

    def _legacy_bytes(self, task):
        # Reproduce exactly what an older (pre-envelope) producer wrote:
        # a pickled bare Message, no version tag.
        message = self.huey._registry._create_message(task)
        return self.huey.serializer.serialize(message)

    def _current_bytes(self, task):
        return self.huey.serialize_task(task)

    def _unknown_version_bytes(self, task):
        # A structurally valid envelope stamped with a version this build
        # cannot read.
        message = self.huey._registry._create_message(task)
        envelope = Envelope(99, message)
        return self.huey.serializer.serialize(envelope)

    def _corrupt_bytes(self):
        return b'\x00\x01not-a-valid-pickle-stream'

    def test_mixed_queue_executes_in_order_and_preserves_args(self):
        calls, add, follow = self._make_tasks()

        # Phase 1: pre-seed the temporary queue with legacy records only,
        # including a pipeline (task with a follow-up) and a scheduled task.
        legacy_pipeline = add.s(1, 2, tag='legacy-pipe').then(
            follow, source='legacy-pipe')
        eta = datetime.datetime.now() + datetime.timedelta(hours=1)
        legacy_scheduled = add.s(3, 4, tag='legacy-sched', eta=eta)
        legacy_plain = add.s(5, 6, tag='legacy-plain')

        self.huey.storage.enqueue(self._legacy_bytes(legacy_pipeline))
        self.huey.storage.enqueue(self._legacy_bytes(legacy_plain))
        self.huey.storage.add_to_schedule(
            self._legacy_bytes(legacy_scheduled), eta)

        # Phase 2: producers are upgraded and write version-2 records.
        current_pipeline = add.s(7, 8, tag='current-pipe').then(
            follow, source='current-pipe')
        current_plain = add.s(9, 10, tag='current-plain')
        self.huey.enqueue(current_pipeline)
        self.huey.enqueue(current_plain)

        self.assertEqual(len(self.huey), 4)
        self.assertEqual(self.huey.scheduled_count(), 1)

        # Drain the live queue. FIFO order must be preserved across both
        # payload generations.
        order = []
        for _ in range(4):
            task = self.huey.dequeue()
            order.append((task.kwargs.get('tag'), task.args))
            self.huey.execute(task)

        self.assertEqual(order, [
            ('legacy-pipe', (1, 2)),
            ('legacy-plain', (5, 6)),
            ('current-pipe', (7, 8)),
            ('current-plain', (9, 10)),
        ])

        # Follow-up tasks generated by both pipeline generations were
        # enqueued as their heads completed. Drain them and check that the
        # upstream return values were extended into their args.
        self.assertEqual(self.huey.pending_count(), 2)
        follow_order = []
        while self.huey.pending_count():
            follow_task = self.huey.dequeue()
            follow_order.append(
                (follow_task.kwargs.get('source'), follow_task.args))
            self.huey.execute(follow_task)

        self.assertEqual(follow_order, [
            ('legacy-pipe', (3,)),
            ('current-pipe', (15,)),
        ])

        # Every argument set from both generations round-tripped intact.
        self.assertIn((1, 2, 'legacy-pipe'), calls)
        self.assertIn((5, 6, 'legacy-plain'), calls)
        self.assertIn((7, 8, 'current-pipe'), calls)
        self.assertIn((9, 10, 'current-plain'), calls)
        self.assertIn(('follow', 3, 'legacy-pipe'), calls)
        self.assertIn(('follow', 15, 'current-pipe'), calls)

        # The legacy scheduled record decodes with its original eta and
        # parameters intact.
        scheduled = self.huey.read_schedule(
            datetime.datetime.now() + datetime.timedelta(hours=2))
        self.assertEqual(len(scheduled), 1)
        task = scheduled[0]
        self.assertEqual(task.id, legacy_scheduled.id)
        self.assertEqual(task.args, (3, 4))
        self.assertEqual(task.kwargs, {'tag': 'legacy-sched'})
        self.assertEqual(task.eta, eta)
        self.assertEqual(self.huey.scheduled_count(), 0)

    def test_unknown_version_goes_to_dead_letter_without_blocking(self):
        calls, add, follow = self._make_tasks()
        dead = []

        @self.huey.signal(SIGNAL_DEAD_LETTER)
        def on_dead(signal, task, letter):
            dead.append(letter)

        # Queue: healthy legacy, unknown version, healthy current.
        poison = self._unknown_version_bytes(add.s(2, 2, tag='poison'))
        self.huey.storage.enqueue(
            self._legacy_bytes(add.s(1, 1, tag='before')))
        self.huey.storage.enqueue(poison)
        self.huey.enqueue(add.s(3, 3, tag='after'))

        self.assertEqual(len(self.huey), 3)

        # First record is a normal legacy task.
        first = self.huey.dequeue()
        self.assertEqual(first.kwargs['tag'], 'before')
        self.huey.execute(first)

        # The unknown-version record is removed from the live queue and
        # quarantined; dequeue() signals "empty slot" rather than raising.
        self.assertIsNone(self.huey.dequeue())
        self.assertEqual(len(self.huey), 1)
        self.assertEqual(self.huey.dead_letter_count(), 1)

        # The healthy record behind the bad one still runs.
        after = self.huey.dequeue()
        self.assertEqual(after.kwargs['tag'], 'after')
        self.huey.execute(after)
        self.assertEqual(len(self.huey), 0)

        letters = self.huey.dead_letters()
        self.assertEqual(len(letters), 1)
        letter = letters[0]
        self.assertEqual(letter.version, 99)
        self.assertEqual(letter.source, 'queue')
        self.assertIn('UnknownTaskVersion', letter.error)
        self.assertEqual(letter.raw, poison)
        self.assertEqual(dead, [letter])

        # The dead letter can be located by id and inspected directly.
        fetched = self.huey.get_dead_letter(letter.id)
        self.assertEqual(fetched, letter)

    def test_corrupt_bytes_are_quarantined_as_unknown_version(self):
        calls, add, follow = self._make_tasks()
        corrupt = self._corrupt_bytes()
        self.huey.storage.enqueue(corrupt)
        self.huey.enqueue(add.s(4, 5))

        self.assertIsNone(self.huey.dequeue())
        letter, = self.huey.dead_letters()
        self.assertEqual(letter.version, TASK_PAYLOAD_VERSION_UNKNOWN)
        self.assertIn('InvalidTaskPayload', letter.error)
        self.assertEqual(letter.raw, corrupt)

        # Traffic behind the corrupt record is unaffected.
        task = self.huey.dequeue()
        self.assertEqual(task.args, (4, 5))
        self.assertEqual(self.huey.execute(task), 9)

    def test_scheduled_bad_record_is_quarantined_with_sources(self):
        calls, add, follow = self._make_tasks()
        eta = datetime.datetime.now()
        self.huey.storage.add_to_schedule(
            self._unknown_version_bytes(add.s(1)), eta)
        self.huey.storage.add_to_schedule(
            self._legacy_bytes(add.s(2, tag='ok')), eta)

        tasks = self.huey.read_schedule(eta + datetime.timedelta(seconds=1))
        self.assertEqual(len(tasks), 1)
        self.assertEqual(tasks[0].kwargs['tag'], 'ok')

        letter, = self.huey.dead_letters()
        self.assertEqual(letter.source, 'schedule')
        self.assertEqual(letter.version, 99)

    def test_peeking_does_not_duplicate_dead_letters(self):
        calls, add, follow = self._make_tasks()
        corrupt = self._corrupt_bytes()
        self.huey.storage.enqueue(corrupt)
        self.huey.enqueue(add.s(1))

        # pending() is a non-destructive peek: the corrupt record stays in the
        # queue and must not generate (or duplicate) dead-letter entries.
        self.assertEqual(self.huey.pending_count(), 2)
        healthy = self.huey.pending()
        self.assertEqual(len(healthy), 1)
        self.assertEqual(healthy[0].args, (1,))
        self.assertEqual(self.huey.dead_letter_count(), 0)
        self.assertEqual(self.huey.pending_count(), 2)

        # The destructive dequeue path parks it exactly once.
        self.assertIsNone(self.huey.dequeue())
        self.assertEqual(self.huey.dead_letter_count(), 1)
        self.assertEqual(self.huey.pending_count(), 1)

    def test_dead_letter_replay_and_delete(self):
        calls, add, follow = self._make_tasks()
        self.huey.storage.enqueue(
            self._unknown_version_bytes(add.s(1)))
        self.assertIsNone(self.huey.dequeue())
        letter, = self.huey.dead_letters()

        # Replaying pushes the original raw bytes back onto the live queue.
        # With this build it still cannot decode, so it is re-quarantined
        # under a new dead-letter id.
        self.assertTrue(self.huey.replay_dead_letter(letter.id))
        self.assertEqual(self.huey.dead_letter_count(), 0)
        self.assertEqual(len(self.huey), 1)
        self.assertIsNone(self.huey.dequeue())
        self.assertEqual(self.huey.dead_letter_count(), 1)

        new_letter, = self.huey.dead_letters()
        self.assertNotEqual(new_letter.id, letter.id)
        self.assertEqual(new_letter.raw, letter.raw)

        self.assertTrue(self.huey.delete_dead_letter(new_letter.id))
        self.assertEqual(self.huey.dead_letter_count(), 0)
        self.assertFalse(self.huey.delete_dead_letter(new_letter.id))

    def test_dead_letter_disabled_discards_bad_records(self):
        huey = MemoryHuey(utc=False, dead_letter=False)

        @huey.task()
        def add(a, b):
            return a + b

        huey.storage.enqueue(b'corrupt-bytes')
        huey.enqueue(add.s(2, 3))
        self.assertIsNone(huey.dequeue())
        self.assertEqual(huey.dead_letter_count(), 0)
        self.assertEqual(huey.dead_letters(), [])
        self.assertEqual(huey.execute(huey.dequeue()), 5)

    def test_writer_rollback_emits_legacy_payload_again(self):
        calls, add, follow = self._make_tasks()

        # New build writes explicit envelopes by default.
        current = self._current_bytes(add.s(1))
        self.assertIsInstance(pickle.loads(current), Envelope)

        # Roll the producer back to the legacy wire format.
        self.huey.payload_version = TASK_PAYLOAD_V1
        rolled_back = self._current_bytes(add.s(1))
        self.assertIsInstance(pickle.loads(rolled_back), Message)

        # The same dual-version consumer reads both generations.
        self.assertEqual(self.huey.deserialize_task(current).args, (1,))
        self.assertEqual(self.huey.deserialize_task(rolled_back).args, (1,))

    def test_unknown_version_exception_carries_version_for_locating(self):
        @self.huey.task()
        def add(a, b):
            return a + b

        raw = self._unknown_version_bytes(add.s(1))
        obj = self.huey.serializer.deserialize(raw)
        try:
            self.huey._registry.create_task(obj)
        except UnknownTaskVersion as exc:
            self.assertEqual(exc.version, 99)
        else:
            self.fail('UnknownTaskVersion was not raised')

    def test_pickle_failure_surfaces_as_invalid_payload(self):
        with self.assertRaises(InvalidTaskPayload):
            self.huey.deserialize_task(b'not-a-pickle')

    def test_unknown_envelope_is_never_decoded_as_legacy(self):
        # The version gate must run before any Message-specific access. An
        # envelope with an unknown version must never fall through to the
        # legacy bare-Message decoder.
        @self.huey.task()
        def add(a, b):
            return a + b

        raw = self._unknown_version_bytes(add.s(1))
        # The unpickled object is visibly an envelope, not a Message.
        obj = self.huey.serializer.deserialize(raw)
        self.assertNotIsInstance(obj, Message)
        self.assertEqual(identify_payload_version(obj), 99)

        with self.assertRaises(UnknownTaskVersion):
            self.huey.deserialize_task(raw)

    def test_two_generations_share_registration_and_defaults(self):
        # A legacy record and a current record for the same task must both
        # resolve to the registered task class and honor the same default
        # retry/parameter rules.
        @self.huey.task(retries=3, retry_delay=5)
        def add(a, b=10):
            return a + b

        legacy = self.huey.deserialize_task(
            self._legacy_bytes(add.s(2)))
        current = self.huey.deserialize_task(
            self._current_bytes(add.s(2)))

        for task in (legacy, current):
            self.assertEqual(type(task), type(add.s(0)))
            self.assertEqual(task.retries, 3)
            self.assertEqual(task.retry_delay, 5)
            self.assertEqual(task.args, (2,))
            self.assertEqual(task.kwargs, {})
            self.assertEqual(task.execute(), 12)  # Default b=10 applied.

    def test_flush_dead_letters_only_removes_dlq_records(self):
        calls, add, follow = self._make_tasks()
        corrupt = self._corrupt_bytes()
        self.huey.storage.enqueue(corrupt)
        self.huey.put_result('keep-me', 'value')
        self.assertIsNone(self.huey.dequeue())
        self.assertEqual(self.huey.dead_letter_count(), 1)

        self.huey.flush_dead_letters()
        self.assertEqual(self.huey.dead_letter_count(), 0)
        # Ordinary result-store entries are untouched.
        self.assertEqual(self.huey.get('keep-me'), 'value')

    def test_worker_loop_quarantines_and_keeps_processing(self):
        # Drive the actual consumer Worker implementation: a poison record
        # must be quarantined inside a single loop() call and the following
        # healthy record must run on the next call, with no exception raised.
        calls, add, follow = self._make_tasks()
        self.huey.storage.enqueue(self._corrupt_bytes())
        self.huey.enqueue(add.s(6, 7))

        consumer = self.consumer(workers=1)
        worker, _ = consumer.worker_threads[0]
        self.assertIsInstance(worker, Worker)

        # First loop parks the corrupt record in the DLQ (no raise).
        worker.loop()
        self.assertEqual(self.huey.dead_letter_count(), 1)
        self.assertEqual(len(self.huey), 1)

        # Second loop processes the healthy record behind it.
        worker.loop()
        self.assertEqual(len(self.huey), 0)
        self.assertIn((6, 7, None), calls)

